"""Shared PIL and MediaArtifact helpers for L6 media generation engines."""

from __future__ import annotations

import hashlib
import io
import time
from pathlib import Path
from typing import Any, Dict, Union

from PIL import Image

try:
    from cognitive.output.media_gen.core.models import MediaArtifact, MediaRequest, MediaType
    from cognitive.output.media_gen.engines.base import BaseMediaEngine
except ImportError:
    from media_gen.core.models import MediaArtifact, MediaRequest, MediaType
    from media_gen.engines.base import BaseMediaEngine


def load_image_input(source: Union[bytes, str, Path, Image.Image, None], fallback_size=(256, 256)) -> Image.Image:
    """Decode bytes/path/Image into an RGB PIL Image, or create a clean canvas if None."""
    if source is None:
        return Image.new("RGB", fallback_size, color=(64, 96, 128))
    if isinstance(source, Image.Image):
        return source.convert("RGB")
    if isinstance(source, (bytes, bytearray)):
        return Image.open(io.BytesIO(bytes(source))).convert("RGB")
    return Image.open(Path(source)).convert("RGB")


def encode_png(image: Image.Image) -> bytes:
    """Serialize a PIL Image into PNG bytes."""
    buf = io.BytesIO()
    image.save(buf, format="PNG")
    return buf.getvalue()


def build_artifact(
    request: MediaRequest,
    raw_bytes: bytes,
    metadata: Dict[str, Any],
    ext: str = "png",
    mime_type: str = "image/png",
) -> MediaArtifact:
    """Create a SHA-256 verified MediaArtifact from generated bytes."""
    digest = hashlib.sha256(raw_bytes).hexdigest()
    enriched = dict(metadata)
    enriched["created_at"] = time.time()
    return MediaArtifact(
        request_id=request.id,
        media_type=MediaType.IMAGE,
        uri=f"file:///storage/media/images/{digest[:16]}.{ext}",
        mime_type=mime_type,
        size_bytes=len(raw_bytes),
        sha256=digest,
        metadata=enriched,
    )

