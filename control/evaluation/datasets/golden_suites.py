"""Golden and Regression Suites for CI (Layer 11: Evaluation & Quality, Feature 11.03).

Provides:
- Golden suite compilation and execution
- Regression diff against baseline runs
- CI pass/fail quality gating
"""

from __future__ import annotations

import time
from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Any, Callable, Dict, List, Optional, Union

from .custom_scorer import BaseScorer, ExactMatchScorer, ScorerResult
from .dataset_store import DatasetSample, EvaluationDataset


@dataclass
class GoldenSampleResult:
    """Evaluation result for one test sample in a golden suite."""
    sample_id: str
    domain: str
    prompt: str
    prediction: str
    reference: Optional[str]
    scorer_result: ScorerResult
    duration_ms: float


@dataclass
class GoldenSuiteReport:
    """Report generated by running candidate model against a golden suite."""
    suite_id: str
    name: str
    passed: bool
    total_samples: int
    passed_samples: int
    pass_rate: float
    threshold: float
    sample_results: List[GoldenSampleResult] = field(default_factory=list)
    failures: List[Dict[str, Any]] = field(default_factory=list)
    timestamp: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())


@dataclass
class GoldenSuite:
    """Golden baseline evaluation suite definition."""
    suite_id: str
    name: str
    datasets: List[EvaluationDataset]
    default_scorer: BaseScorer = field(default_factory=ExactMatchScorer)
    pass_threshold: float = 0.90  # Default 90% required to pass CI
    metadata: Dict[str, Any] = field(default_factory=dict)


class GoldenSuiteRunner:
    """Executes evaluation runs against defined golden suites."""

    def __init__(self, suite: GoldenSuite):
        self.suite = suite

    def run(
        self,
        model_callable: Union[Callable[[str], str], Any],
        custom_scorers: Optional[Dict[str, BaseScorer]] = None,
    ) -> GoldenSuiteReport:
        sample_results: List[GoldenSampleResult] = []
        failures: List[Dict[str, Any]] = []

        all_samples: List[DatasetSample] = []
        for ds in self.suite.datasets:
            all_samples.extend(ds.samples)

        for sample in all_samples:
            t0 = time.perf_counter()
            if hasattr(model_callable, "predict"):
                prediction = str(model_callable.predict(sample.input_prompt))
            elif callable(model_callable):
                prediction = str(model_callable(sample.input_prompt))
            else:
                prediction = str(model_callable)
            duration_ms = (time.perf_counter() - t0) * 1000.0

            # Select scorer: check custom map by domain or sample tag, else default
            scorer = self.suite.default_scorer
            if custom_scorers and sample.domain in custom_scorers:
                scorer = custom_scorers[sample.domain]

            res = scorer.score(prediction, sample.expected_output, sample.metadata)

            sample_result = GoldenSampleResult(
                sample_id=sample.sample_id,
                domain=sample.domain,
                prompt=sample.input_prompt,
                prediction=prediction,
                reference=sample.expected_output,
                scorer_result=res,
                duration_ms=duration_ms,
            )
            sample_results.append(sample_result)

            if not res.passed:
                failures.append({
                    "sample_id": sample.sample_id,
                    "prompt": sample.input_prompt,
                    "prediction": prediction,
                    "reference": sample.expected_output,
                    "reason": res.reason,
                })

        total = len(sample_results)
        passed_count = sum(1 for s in sample_results if s.scorer_result.passed)
        pass_rate = (passed_count / total) if total > 0 else 1.0
        suite_passed = pass_rate >= self.suite.pass_threshold

        return GoldenSuiteReport(
            suite_id=self.suite.suite_id,
            name=self.suite.name,
            passed=suite_passed,
            total_samples=total,
            passed_samples=passed_count,
            pass_rate=round(pass_rate, 4),
            threshold=self.suite.pass_threshold,
            sample_results=sample_results,
            failures=failures,
        )
